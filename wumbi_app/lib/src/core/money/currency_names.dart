import 'currency_type.dart';

/// Localised [CurrencyType] names per app language (CLDR wording). English
/// lives on the enum (`displayName`) and is the fallback for any language or
/// code missing here.
extension CurrencyTypeName on CurrencyType {
  /// Name in [localeName] (`fr`, `fr_FR`, `pt-BR`…); English fallback.
  String nameIn(String localeName) {
    final lang = localeName.split(RegExp('[_-]')).first.toLowerCase();
    return _currencyNames[lang]?[code] ?? displayName;
  }

  /// Localised name and English name — for search, so `dollar` finds USD
  /// whatever the app language.
  bool nameMatches(String localeName, String query) {
    final q = query.toLowerCase();
    return code.toLowerCase().contains(q) ||
        displayName.toLowerCase().contains(q) ||
        nameIn(localeName).toLowerCase().contains(q);
  }
}

