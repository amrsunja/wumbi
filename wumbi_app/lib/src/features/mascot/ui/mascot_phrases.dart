      MascotPhrase.walletUp => l10n.mascot_wallet_up(amount),
      MascotPhrase.walletSleeping => l10n.mascot_wallet_sleeping,
      MascotPhrase.walletCalm => l10n.mascot_wallet_calm,
      MascotPhrase.budgetsOver => l10n.mascot_budgets_over(n),
