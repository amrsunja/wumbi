      MascotPhrase.chargeTomorrow => l10n.mascot_charge_tomorrow(charged(), amount),
      MascotPhrase.chargeSoon => l10n.mascot_charge_soon(charged(), amount),
      MascotPhrase.debtDueToday => l10n.mascot_debt_due_today(name),
      MascotPhrase.debtDueTomorrow => l10n.mascot_debt_due_tomorrow(name),
      MascotPhrase.debtDueSoon => l10n.mascot_debt_due_soon(name, n),
      MascotPhrase.insightMover => l10n.mascot_insight_mover(name, n),
      MascotPhrase.insightUntagged => l10n.mascot_insight_untagged(n),
