      MascotPhrase.ansUpcoming => l10n.mascot_ans_upcoming(amount, n),
      MascotPhrase.ansNothingUpcoming => l10n.mascot_ans_nothing_upcoming,
      MascotPhrase.ansOwed => l10n.mascot_ans_owed(amount, name),
      MascotPhrase.ansNobodyOwes => l10n.mascot_ans_nobody_owes,
      MascotPhrase.ansReserveLow => l10n.mascot_ans_reserve_low,
