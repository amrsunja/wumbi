      MascotPhrase.tipRainyDay => l10n.mascot_tip_rainy_day,
      MascotPhrase.tipPayYourselfFirst => l10n.mascot_tip_pay_yourself_first,
      MascotPhrase.insightIncomeUp => l10n.mascot_insight_income_up(n),
      MascotPhrase.insightTagYearly => l10n.mascot_insight_tag_yearly(name, amount),
      MascotPhrase.tipTreat => l10n.mascot_tip_treat,
      MascotPhrase.tipFutureSelf => l10n.mascot_tip_future_self(amount, l.amount2?.format() ?? ''),
      MascotPhrase.insightNoSpendYesterday => l10n.mascot_insight_no_spend_yesterday,
    };
    // Templates may start with a lower-case name ("a subscription …").
    return s.isEmpty ? s : '${s[0].toUpperCase()}${s.substring(1)}';
  }
}
