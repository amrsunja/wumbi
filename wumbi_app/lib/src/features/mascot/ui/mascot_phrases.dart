/// Every hamster sentence in the app language. Templates are written per
/// language (ICU in the arb files), never translated word for word.
abstract class MascotPhrases {
  static String text(AppLocale l10n, MascotLine line) {
    final first = _one(l10n, line);
    final then = line.then;
    return then == null ? first : '$first ${_one(l10n, then)}';
  }

  /// Quick-reply label: what the user asks.
  static String question(AppLocale l10n, MascotQuestion q) => switch (q) {
        MascotQuestion.today => l10n.mascot_q_today,
        MascotQuestion.yesterday => l10n.mascot_q_yesterday,
        MascotQuestion.week => l10n.mascot_q_week,
        MascotQuestion.month => l10n.mascot_q_month,
        MascotQuestion.where => l10n.mascot_q_where,
        MascotQuestion.biggest => l10n.mascot_q_biggest,
        MascotQuestion.budgets => l10n.mascot_q_budgets,
        MascotQuestion.upcoming => l10n.mascot_q_upcoming,
        MascotQuestion.owed => l10n.mascot_q_owed,
        MascotQuestion.reserve => l10n.mascot_q_reserve,
        MascotQuestion.tip => l10n.mascot_q_tip,
        MascotQuestion.joke => l10n.mascot_q_joke,
      };

  static String? actionLabel(AppLocale l10n, MascotAction? action) => switch (action?.kind) {
        null => null,
        MascotActionKind.addTransaction => l10n.mascot_action_add,
        _ => l10n.mascot_action_view,
      };

